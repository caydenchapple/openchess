import { h } from '../util.js';
import { Board } from '../board.js';
import { get } from '../store.js';
import { net } from '../net.js';

export function mount(root) {
  const st = get();
  const demo = h('div', { class: 'board-demo' });
  const boardEl = h('div', { class: 'boardwrap' });
  demo.append(boardEl);
  const returning = st.games.length > 0;

  const feature = (icon, title, text) => h('div', { class: 'card feature' }, h('h3', {}, `${icon} ${title}`), h('p', { class: 'muted', style: { margin: 0 } }, text));

  root.append(h('div', { class: 'stack' },
    h('section', { class: 'hero' },
      h('div', { class: 'stack' },
        h('span', { class: 'pill' }, 'Free · Open source · No sign-up'),
        h('h1', {}, 'Play chess. Then actually get better.'),
        h('p', { class: 'lead' }, 'Play the computer or real people online. After every game you get an engine-checked review, an accuracy score, an estimated rating and lessons to help you improve.'),
        h('div', { class: 'row' },
          h('a', { class: 'btn primary big', href: '#/play' }, '♞ Play now'),
          h('a', { class: 'btn big', href: returning ? '#/history' : '#/review/import' }, returning ? 'Review a game' : 'Review a PGN')),
        returning && h('p', { class: 'muted small' }, `Welcome back, ${st.player.name} — ${st.ratings.computer.r} vs computer · ${st.ratings.online.r} online.`)),
      demo),
    h('div', { class: 'grid three' },
      feature('⚔️', 'Play anyone, free', 'Quick pairing or a private invite link for a friend. No account — just pick a name and play.'),
      feature('🤖', 'Stockfish in your browser', '12 levels from complete beginner to near-full strength. Runs locally, so it works even if you go offline.'),
      feature('📊', 'Honest game review', 'Every move rated best → blunder, accuracy per phase, evaluation graph and an estimated performance rating.'),
      feature('🎓', 'A coach that explains', 'Plain-English lessons, explanations of your key mistakes, opening notes and a personal training plan — all generated by code in your browser, no AI service.'),
      feature('🧩', 'Train on your own mistakes', 'Every blunder becomes a puzzle. Fix the positions you actually got wrong.'),
      feature('🔒', 'Private by design', 'Your games, ratings and settings live in this browser. Export or delete them any time.')),
    ));

  const b = new Board(boardEl, { orientation: 'w' });
  b.setPosition('r1bqk2r/pppp1ppp/2n2n2/2b1p3/2B1P3/2NP1N2/PPP2PPP/R1BQK2R b KQkq - 0 5', { lastMove: ['d2', 'd3'] });
  b.setInteractive(null);
  b.setArrows([{ from: 'e8', to: 'g8', brush: 'green' }]);

  net.connect();
  return () => b.destroy();
}

export function mountAbout(root) {
  root.append(h('div', { class: 'card stack', style: { maxWidth: '760px' } },
    h('h1', {}, 'About OpenChess'),
    h('p', {}, 'OpenChess is a free, open-source chess site with no accounts, no ads and no paywall. It is licensed GPL-3.0-or-later.'),
    h('h3', {}, 'How reviews work'),
    h('p', {}, 'Stockfish 19 (lite NNUE, WebAssembly) analyses every position of your game in your browser at depth 12. Move quality comes from the change in win probability (the same curve Lichess uses). The "performance rating" is a rough estimate from average centipawn loss — treat it as a ballpark, not an official rating.'),
    h('h3', {}, 'The coach'),
    h('p', {}, 'The coach is ordinary code, not an AI model: it reads Stockfish\'s numbers and the rules of chess to explain why a move was weak (hung piece, missed tactic, missed mate, a slipped advantage), writes lessons from the patterns in your games, and keeps hand-written notes on the main openings. Nothing is sent anywhere, and it never makes up moves — but it only covers the common cases, so treat its explanations as a starting point.'),
    h('h3', {}, 'Ratings'),
    h('p', {}, 'Your rating is a local Elo stored in your browser (separate pools for computer and online games), so it is not comparable with FIDE, Lichess or Chess.com ratings and cannot be verified by others.'),
    h('h3', {}, 'Privacy'),
    h('p', {}, 'No accounts, no cookies, no analytics. Games and settings are saved in localStorage. Online games exchange only moves, your chosen display name and your local rating. Reviews and coaching run entirely in your browser.'),
    h('p', {}, h('a', { href: '#/play' }, 'Play a game →'))));
  return () => {};
}
